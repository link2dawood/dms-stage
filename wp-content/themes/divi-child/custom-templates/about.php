            return;
        }
    });
}

// Function to get directions
function getDirections() {
    const locationInput = document.getElementById('user-address-autocomplete').value;

    // Make sure the user has entered a location
    if (!locationInput) {
        alert('Please enter a location.');
        return;
    }

    // Use the Google Maps Directions API to get directions
    const directionsURL = `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(companyLocation)}&origin=${encodeURIComponent(locationInput)}`;
    
     // Open the directions in a new tab
     window.open(directionsURL, '_blank');
}


